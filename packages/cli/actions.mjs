/**
 * Run a route's `action` for a POST, in the dev and preview servers.
 *
 * The client cannot call an action — a `.server.hys` is not in the client
 * bundle — so the browser POSTs a form and this is what answers. That is what
 * makes the flow work with JavaScript disabled, and it is why an action is a
 * server thing in this design rather than a function a component calls.
 *
 * The actions are bundled ahead of time by `buildActionBundle` into one ESM file
 * with a table keyed by route pattern, so this module only has to load it and
 * dispatch. No second compiler, no second router: the pattern matching comes
 * from `router-core.js`, the same one the browser uses.
 */

import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);

import { matchRoute } from '../../runtime/router-core.js';
import { routesEsbuildPlugin } from './router.mjs';

/**
 * The bundle source for every action in the project.
 *
 * A route with no `action` export simply is not in the table, and posting to it
 * is a 405 rather than a silent success.
 */
export function actionBundleSource(table, pairs) {
  const lines = [
    '// [xihanzu-NR]',
    '// GENERATED by `hydra build` — the action table for the dev/preview server.',
    '//',
    '// Each loader/action is called with ONE argument, an event object:',
    '//',
    '//   export async def loader(event):',
    '//       slug = event.params.get("slug")',
    '//       return {"post": ...}',
    '//',
    '// `event.params` is a dict of the URL parameters, `event.url` the path, and',
    '// `event.request` carries method/headers/body for an action.',
    '',
  ];

  const identFor = (() => {
    const seen = new Map();
    return (f) => {
      if (seen.has(f)) return seen.get(f);
      let h = 0;
      for (let i = 0; i < f.length; i++) h = (h * 31 + f.charCodeAt(i)) | 0;
      const id = `__a_${Math.abs(h).toString(36)}`;
      seen.set(f, id);
      return id;
    };
  })();

  // ONE identifier per server file, keyed by its pages-relative name — the same
  // key the route table uses.
  //
  // An earlier version called this helper with the relative name for the import
  // and with the absolute path for the table, producing two identifiers for one
  // module (`__a_8dz3pd` and `__a_rzvsvn`). The bundle then imported a name it
  // never used, and every POST answered "no action for this route" against a
  // bundle that plainly contained the action.
  const idByRelative = new Map();
  for (const [rel, abs] of pairs) {
    const id = identFor(rel);
    idByRelative.set(rel, id);
    lines.push(`import * as ${id} from ${JSON.stringify(abs)};`);
  }

  lines.push('');
  lines.push('export const routes = ' + JSON.stringify(
    table.routes.map((r) => ({
      pattern: r.pattern,
      file: r.file,
      params: r.params,
      segments: r.segments,
      serverFile: r.serverFile || null,
    })),
  ) + ';');
  lines.push('');
  lines.push('const actions = {');
  for (const r of table.routes) {
    const id = r.serverFile ? idByRelative.get(r.serverFile) : null;
    if (!id) continue;
    lines.push(`  ${JSON.stringify(r.pattern)}: ${id}.action || null,`);
  }
  lines.push('};');
  lines.push('');
  lines.push('export const loaders = {');
  for (const r of table.routes) {
    const id = r.serverFile ? idByRelative.get(r.serverFile) : null;
    if (!id) continue;
    lines.push(`  ${JSON.stringify(r.pattern)}: ${id}.loader || null,`);
  }
  lines.push('};');
  lines.push('');
  lines.push('export function actionFor(url) {');
  lines.push('  const hit = match(url);');
  lines.push('  if (!hit) return null;');
  lines.push('  const fn = actions[hit.route.pattern];');
  lines.push('  if (!fn) return null;');
  lines.push('  return { fn, params: hit.params, pattern: hit.route.pattern };');
  lines.push('}');
  lines.push('');
  lines.push('export function loaderFor(url) {');
  lines.push('  const hit = match(url);');
  lines.push('  if (!hit) return null;');
  lines.push('  const fn = loaders[hit.route.pattern];');
  lines.push('  if (!fn) return null;');
  lines.push('  return { fn, params: hit.params, pattern: hit.route.pattern };');
  lines.push('}');
  lines.push('');
  lines.push('function match(url) {');
  lines.push('  for (const route of routes) {');
  lines.push('    const params = matchSegments(split(url), route.segments);');
  lines.push('    if (params) return { route, params };');
  lines.push('  }');
  lines.push('  return null;');
  lines.push('}');
  lines.push('function split(url) {');
  lines.push('  const clean = ("/" + String(url || "/").replace(/^\\/+/, "")).replace(/\\/+$/, "");');
  lines.push('  return clean === "/" ? [] : clean.slice(1).split("/");');
  lines.push('}');
  lines.push('function matchSegments(parts, pattern) {');
  lines.push('  const params = {}; let i = 0;');
  lines.push('  for (const seg of pattern) {');
  lines.push('    if (seg.kind === "group") continue;');
  lines.push('    if (seg.kind === "catchall") { params[seg.name] = parts.slice(i); return params; }');
  lines.push('    if (i >= parts.length) return null;');
  lines.push('    const v = parts[i++];');
  lines.push('    if (seg.kind === "param") params[seg.name] = v;');
  lines.push('    else if (seg.value !== v) return null;');
  lines.push('  }');
  lines.push('  return i === parts.length ? params : null;');
  lines.push('}');
  lines.push('');
  return lines.join('\n');
}

/**
 * Write the action bundle and return a loader, or null when nothing has actions.
 *
 * Written into `.hydra/` like the route table, and loaded on demand: a project
 * with no actions never pays for the file or the import.
 */
export function writeActionBundle(cwd, table) {
  const withActions = table.routes.filter((r) => r.serverFile);
  if (withActions.length === 0) return null;
  const dir = path.join(cwd, '.hydra');
  fs.mkdirSync(dir, { recursive: true });
  // The SOURCE is `.mjs`-shaped but not runnable: it imports `.hys` files and
  // node has no loader for those. It is the ENTRY for `bundleActions` below,
  // which turns it into one real module the server can `require`.
  const entry = path.join(dir, 'actions.entry.mjs');
  // The tuple is (pages-relative, absolute): the relative name is the KEY the
  // route table uses, the absolute one is what the generated module imports.
  const pairs = withActions.map((r) => [
    r.serverFile,
    path.resolve(table.root, r.serverFile).split(path.sep).join('/'),
  ]);
  fs.writeFileSync(entry, actionBundleSource(table, pairs), 'utf8');
  return entry;
}

/**
 * Bundle the action entry into a module node can actually load.
 *
 * `esbuild` and the compiler plugin come from the caller, so this file stays a
 * description of WHAT to build rather than a second place that resolves the
 * toolchain.
 */
export async function bundleActions(
  esbuild,
  entry,
  { outfile, cwd, pkgRoot, hydraAlias, serverAlias, compilerPlugin },
) {
  if (!entry) return null;
  await esbuild.build({
    entryPoints: [entry],
    bundle: true,
    write: true,
    // CommonJS: the runtime it pulls in is CJS after bundling, and the server
    // loads the result with `require`, which needs no loader and no cache
    // busting query string.
    format: 'cjs',
    platform: 'node',
    target: 'node18',
    outfile,
    jsx: 'automatic',
    logLevel: 'silent',
    nodePaths: [path.join(cwd, 'node_modules'), path.join(pkgRoot, 'node_modules')],
    resolveExtensions: ['.hyx', '.hys', '.hsx', '.hs', '.mjs', '.js', '.jsx', '.ts', '.tsx', '.json'],
    plugins: [
      {
        name: 'hydra-runtime-specifiers',
        setup(build) {
          build.onResolve({ filter: /^hydra(\/[a-z]+)?$/ }, (args) => {
            if (args.path === 'hydra') return { path: hydraAlias };
            if (args.path === 'hydra/server') return { path: serverAlias };
            return null;
          });
        },
      },
      compilerPlugin(),
      // `hydra` imports `hydra:routes` statically, so any bundle that pulls the
      // runtime in needs this plugin too. Without it the action bundle failed to
      // build — which is how the coupling was found.
      // The action bundle has no routes of its own; it needs them only so the
      // runtime's static import resolves.
      routesEsbuildPlugin({ root: cwd, routes: [], layouts: {}, notFound: [], errors: [], errors_diagnostics: [], serverFiles: [] }, { base: '/', cwd }),
    ],
  });
  return outfile;
}

/**
 * Read the request body as text, bounded so a huge POST cannot exhaust memory.
 *
 * A body over the limit is a CLIENT error with an answer: the promise rejects
 * with `error.status = 413` and the request is left readable enough for the
 * caller to write that answer. The first version called `req.destroy()` inside
 * the `data` handler, which killed the socket before `writeHead(413)` could
 * reach it — the client saw "empty reply from server" and no status at all.
 * Pausing instead lets the header go out; `Connection: close` then ends the
 * exchange without reading the rest of a body we have already refused.
 */
export function readBody(req, limitBytes = 1024 * 1024) {
  return new Promise((resolve, reject) => {
    let size = 0;
    let settled = false;
    const chunks = [];
    const fail = (err) => {
      if (settled) return;
      settled = true;
      // Stop consuming. `destroy()` is the caller's decision, after the reply.
      req.pause();
      reject(err);
    };
    req.on('data', (c) => {
      if (settled) return;
      size += c.length;
      if (size > limitBytes) {
        const err = new Error(`body larger than ${limitBytes} bytes`);
        err.status = 413;
        err.limit = limitBytes;
        fail(err);
        return;
      }
      chunks.push(c);
    });
    req.on('end', () => {
      if (settled) return;
      settled = true;
      resolve(Buffer.concat(chunks).toString('utf8'));
    });
    req.on('error', fail);
  });
}

/**
 * A `Request`-shaped object for an action, from a node request.
 *
 * Only what an action can honestly rely on: the method, the URL, the headers and
 * the parsed body. Not a real `Request` — claiming that would mean claiming
 * `fetch` semantics this does not implement.
 *
 * An empty body is `{}`, not `null`. A POST with no body is a legal request (a
 * button that only needs to say "do it"), and the documented idiom
 * `body.get("text")` / `body["text"]` turning into a 500 on
 * "Cannot read properties of null" made the framework look broken for a request
 * it had accepted. A body that is present but unparseable is reported as a
 * client error (`body_error`), not silently turned into `{}`: those two are
 * different requests and only one of them is the caller's mistake.
 */
export function requestFor(req, url, rawBody) {
  const contentType = String(req.headers['content-type'] || '');
  let body = {};
  let body_error = null;
  if (rawBody) {
    if (contentType.includes('application/json')) {
      try {
        body = JSON.parse(rawBody);
      } catch (e) {
        body = {};
        body_error = `invalid JSON body: ${e.message}`;
      }
    } else if (contentType.includes('form')) {
      // Both shapes, on purpose. A form body IS a `URLSearchParams` to the web
      // platform, so `.get("field")` is the accessor an action expects; a plain
      // object is what a HydraScript author reaches for by habit. One object
      // with both, so neither is a surprise.
      const params = new URLSearchParams(rawBody);
      const obj = Object.fromEntries(params);
      obj.get = (k, fallback = null) => (params.has(k) ? params.get(k) : fallback);
      obj.has = (k) => params.has(k);
      body = obj;
    } else {
      body = rawBody;
    }
  }
  return {
    method: req.method || 'GET',
    url,
    headers: req.headers,
    body,
    body_error,
    async json() {
      return body;
    },
    async text() {
      return rawBody || '';
    },
    async form_data() {
      return body instanceof Object ? body : {};
    },
  };
}

/**
 * Load the generated action bundle, if it exists.
 *
 * The cache entry is dropped ONLY during development. `hydra dev` rewrites the
 * bundle on every save, so a cache keyed by path would answer with the previous
 * build's actions for the rest of the session. Production is the opposite case:
 * the bundle is immutable for the life of the process, and re-requiring it per
 * request meant re-evaluating every module — which reset module-level state
 * (connection pools, counters, caches) on every single request and cost real
 * throughput. `HYDRA_DEV` is set by `runDev` itself, so a stray environment
 * variable cannot turn the behaviour on by accident.
 */
export function loadActions(file) {
  if (!file || !fs.existsSync(file)) return null;
  try {
    if (process.env.HYDRA_DEV === '1') {
      delete require.cache[require.resolve(file)];
    }
    return require(file);
  } catch (e) {
    console.error(`[hydra] could not load actions: ${e.message}`);
    return null;
  }
}

