//! Build script: derive the runtime helper list from the runtime itself.
//!
//! `check.rs` needs to know every name `runtime/hydra.ts` exports, because the
//! compiler injects `import { helper } from 'hydra'` on demand and a bare use of
//! one is therefore correct code, not an unbound name. That list used to be a
//! hand-maintained copy in `check.rs` guarded by a test — which is a promise to
//! remember, not a guarantee.
//!
//! Generating it here removes the second source of truth: the list lives in
//! `runtime/hydra.ts` and nowhere else. If the scan ever stops finding exports
//! (a refactor changes the export syntax, say), the build fails loudly instead
//! of silently producing an empty list that would report every runtime helper as
//! an unbound name.

use std::env;
use std::fs;
use std::path::PathBuf;

/// Sanity floor. The runtime exports 160+ value names; anything near zero means
/// the scan is broken, not that the runtime shrank.
const MIN_EXPECTED: usize = 100;

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let runtime = manifest.join("../runtime/hydra.ts");
    println!("cargo:rerun-if-changed={}", runtime.display());

    let src = fs::read_to_string(&runtime).unwrap_or_else(|e| {
        panic!(
            "cannot read {} to build the helper list: {e}\n\
             The list is generated from the runtime so the two cannot drift; \
             without the file the check cannot be built.",
            runtime.display()
        )
    });

    let names = scan_exports(&src);

    if names.len() < MIN_EXPECTED {
        panic!(
            "only {} exported value names found in {}, expected at least {}. \
             The export scan is broken (or the file was rewritten), and the \
             generated list would be wrong in the dangerous direction: every \
             helper missing from it gets reported as an unbound name.",
            names.len(),
            runtime.display(),
            MIN_EXPECTED
        );
    }

    let mut out = String::new();
    out.push_str("// @generated by compiler-rs/build.rs from runtime/hydra.ts. Do not edit.\n");
    out.push_str("pub const RUNTIME_HELPERS: &[&str] = &[\n");
    for n in &names {
        out.push_str(&format!("    \"{n}\",\n"));
    }
    out.push_str("];\n");

    let dest = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR")).join("runtime_helpers.rs");
    fs::write(&dest, out).unwrap_or_else(|e| panic!("cannot write {}: {e}", dest.display()));
}

/// Exported **value** names: `export function f`, `export const x`, and the
/// `export { a, b as c }` form. `export interface` / `export type` are types and
/// cannot be called, so they are not helpers.
fn scan_exports(src: &str) -> Vec<String> {
    let mut out: Vec<String> = Vec::new();
    let mut push = |name: &str| {
        if !name.is_empty() && !out.iter().any(|x| x == name) {
            out.push(name.to_string());
        }
    };

    for line in src.lines() {
        let t = line.trim_start();
        let Some(rest) = t.strip_prefix("export ") else {
            continue;
        };
        let rest = rest.trim_start();
        // `export default function` has no name to import by; `export {` is
        // handled below.
        if rest.starts_with("default ") {
            continue;
        }
        let rest = rest.strip_prefix("async ").unwrap_or(rest).trim_start();
        if rest.starts_with("interface ") || rest.starts_with("type ") || rest.starts_with("declare ")
        {
            continue;
        }
        for kw in ["function ", "const ", "let ", "var ", "class ", "enum "] {
            if let Some(after) = rest.strip_prefix(kw) {
                let name: String = after
                    .chars()
                    .take_while(|c| c.is_alphanumeric() || *c == '_' || *c == '$')
                    .collect();
                push(&name);
                break;
            }
        }
    }

    // `export { a, b as c };` — one line, possibly wrapped by rustfmt-era style
    // but the runtime keeps them on one line each.
    let mut rest = src;
    while let Some(i) = rest.find("export {") {
        rest = &rest[i + "export {".len()..];
        let Some(end) = rest.find('}') else { break };
        let inner = &rest[..end];
        for part in inner.split(',') {
            let part = part.trim();
            if part.is_empty() {
                continue;
            }
            let name = match part.split_once(" as ") {
                Some((_, alias)) => alias.trim(),
                None => part,
            };
            if name.chars().next().is_some_and(|c| c.is_alphabetic() || c == '_' || c == '$') {
                push(name);
            }
        }
        rest = &rest[end + 1..];
    }

    out.sort();
    out
}
